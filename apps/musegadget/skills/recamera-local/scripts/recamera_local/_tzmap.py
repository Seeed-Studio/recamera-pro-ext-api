def timezones_for_country(code: str) -> Optional[List[str]]:
    """IANA candidates for an ISO country code; None when unknown.

    A single-element list is unambiguous; a longer list is a candidate set
    that must be narrowed by another source or by asking the user.
    """
    code = (code or "").strip().upper()
    if not code or code in ("00", "99"):  # regulatory-domain "unset" sentinels
        return None
    if code in SINGLE_ZONE:
        return [SINGLE_ZONE[code]]
    return MULTI_ZONE.get(code)
